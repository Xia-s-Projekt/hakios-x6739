/*
 * Rasterize printable ASCII into an 8x16 1-bit font, written as a C header.
 *
 *   mkfont8x16 > mtkloader/font8x16.h
 *
 * The reference port does this with tools/mkfont8x16.swift (CoreGraphics, Menlo Bold 13pt), which
 * needs macOS. This is the same thing for a Linux host: FreeType renders the glyphs, and the
 * bitmap goes into 8x16 cells the way the loader's console expects -- one byte per row, the
 * leftmost pixel in the top bit.
 *
 * The face is a monospaced bold font: Menlo is the macOS one the reference used and is not on
 * this host, so Liberation Mono Bold stands in for it.
 */
#include <ft2build.h>
#include FT_FREETYPE_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define WIDTH  8
#define HEIGHT 16
#define FIRST  0x20
#define LAST   0x7e
/* the row the letters stand on, counting from the top of the cell: the descenders of g, j, p, q
 * and y hang below it */
#define BASELINE 13

static const char *faces[] = {
	"/usr/share/fonts/liberation/LiberationMono-Bold.ttf",
	"/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf",
	"/usr/share/fonts/liberation/LiberationMono-Regular.ttf",
	NULL,
};

int main(void)
{
	FT_Library library;
	FT_Face face;
	unsigned char cell[HEIGHT][WIDTH];
	int i, code, row, col;

	if (FT_Init_FreeType(&library))
		return 1;
	for (i = 0; faces[i]; i++) {
		if (!FT_New_Face(library, faces[i], 0, &face)) {
			break;
		}
	}
	if (!faces[i]) {
		fprintf(stderr, "mkfont8x16: no monospaced bold font found\n");
		return 1;
	}
	FT_Set_Pixel_Sizes(face, 0, 13);

	printf("/* Generated by tools/mkfont8x16.c: FreeType, ASCII 0x20-0x7e, 8x16, MSB = left. */\n");
	printf("static const unsigned char font8x16[%d][%d] = {\n", LAST - FIRST + 1, HEIGHT);

	for (code = FIRST; code <= LAST; code++) {
		memset(cell, 0, sizeof(cell));
		if (!FT_Load_Char(face, code, FT_LOAD_RENDER | FT_LOAD_TARGET_MONO)) {
			FT_GlyphSlot slot = face->glyph;
			FT_Bitmap *bitmap = &slot->bitmap;
			/* a monospaced face is not always exactly as wide as the cell */
			int x0 = (WIDTH - (int)bitmap->width) / 2 - slot->bitmap_left;
			int y0 = BASELINE - slot->bitmap_top;

			for (row = 0; row < (int)bitmap->rows; row++) {
				int y = y0 + row;
				unsigned char line;

				if (y < 0 || y >= HEIGHT)
					continue;
				line = bitmap->buffer[row * bitmap->pitch];
				for (col = 0; col < (int)bitmap->width; col++) {
					int x = x0 + col;

					if (!(line & (0x80 >> (col & 7))))
						continue;
					if (x >= 0 && x < WIDTH)
						cell[y][x] = 1;
				}
			}
		}
		printf("    { ");
		for (row = 0; row < HEIGHT; row++) {
			unsigned char bits = 0;

			for (col = 0; col < WIDTH; col++) {
				if (cell[row][col])
					bits |= 0x80 >> col;
			}
			printf("%s0x%02x", row ? "," : "", bits);
		}
		printf(" }, /* %c */\n", code == '\\' ? '/' : code);
	}
	printf("};\n");

	FT_Done_Face(face);
	FT_Done_FreeType(library);
	return 0;
}
