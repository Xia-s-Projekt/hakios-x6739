#!/usr/bin/env python3
"""
mkgpufw.py WA OUT.h: the GPU's TTRX_3485 workaround blob, out of YOUR phone (pull-firmware.sh
puts it in fw-gpu/), as a C header the loader carries.

The blob is the vendor's (Arm's, in the vendor's module), so it is not in the repository; the
loader needs it because a Valhall GPU of this revision hangs without the one job it carries.

Its shape (Arm's kbase reads it the same way: drivers/gpu/arm/midgard/mali_kbase_dummy_job_wa.c
in the r32p1 tree):

    0x000  u16 signature 0x4157 ("WA"), u16 version (2), u32 info_offset
    0x008  the payload: the job chain itself, 384 bytes
    0x188  the blob descriptor: base, size, map flags, payload offset, next blob
    0x1a0  the info: job chain address, job slot, blob offset, flags

The header written here is what the loader's GPU job probe needs: the payload's bytes, the
address the chain must be given at, the slot to run it in, and the flags (bit 1: wait for the
cores to come up; bit 2: the logical shader power afterwards).

Usage: mkgpufw.py fw-gpu/valhall-1691526.wa mtkloader/gpufw.h
"""
import struct
import sys


def die(message):
    print("mkgpufw.py: " + message, file=sys.stderr)
    sys.exit(1)


def main():
    if len(sys.argv) != 3:
        die("usage: mkgpufw.py WA OUT.h")

    blob = open(sys.argv[1], "rb").read()
    if len(blob) < 0x1b8:
        die("the blob is too small to be one")

    signature, version, info_offset = struct.unpack_from("<HHI", blob, 0)
    if signature != 0x4157:
        die("the signature is 0x%04x, not 0x4157" % signature)
    if version != 2:
        die("the version is %d, not 2" % version)

    chain, slot, blob_offset, flags = struct.unpack_from("<QIIQ", blob, info_offset)

    # the blob descriptors, a chain of them
    regions = []
    while blob_offset:
        if blob_offset + 24 > len(blob):
            die("the blob descriptor at 0x%x is out of bounds" % blob_offset)
        base, size, map_flags, payload_offset, blob_offset = struct.unpack_from("<QIIII", blob, blob_offset)
        if payload_offset + size > len(blob):
            die("the payload of the blob at 0x%x is out of bounds" % base)
        regions.append((base, size, map_flags, blob[payload_offset:payload_offset + size]))

    if not regions:
        die("the blob carries no region")

    out = []
    out.append("/*")
    out.append(" * Generated by tools/mkgpufw.py: the GPU's TTRX_3485 workaround blob, out of your phone.")
    out.append(" * It is the vendor's, so it is not in the repository; the loader needs it because a Valhall")
    out.append(" * GPU of this revision hangs without the one job it carries.")
    out.append(" */")
    out.append("#ifndef GPUFW_H")
    out.append("#define GPUFW_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("/* the job chain's address in the GPU's address space, and the slot to run it in */")
    out.append("#define GPU_JOB_CHAIN      0x%016xull" % chain)
    out.append("#define GPU_JOB_SLOT       %du" % slot)
    out.append("/* bit 1: wait for the shader cores to come up; bit 2: the logical shader power after */")
    out.append("#define GPU_JOB_FLAGS      0x%016xull" % flags)
    out.append("")
    out.append("/* the regions the blob maps into the GPU's address space, and their bytes */")
    out.append("struct gpu_fw_region {")
    out.append("\tuint64_t base;")
    out.append("\tuint32_t size;")
    out.append("\tuint32_t map_flags;")
    out.append("\tuint32_t bytes;")
    out.append("};")
    out.append("")
    total = 0
    for i, (base, size, map_flags, payload) in enumerate(regions):
        total += len(payload)
        out.append("#define GPU_FW_REGION_%d_BASE      0x%016xull" % (i, base))
        out.append("#define GPU_FW_REGION_%d_SIZE      %du" % (i, size))
        out.append("#define GPU_FW_REGION_%d_MAP_FLAGS 0x%xu" % (i, map_flags))
        out.append("#define GPU_FW_REGION_%d_BYTES     %du" % (i, len(payload)))
    out.append("")
    out.append("static const uint8_t gpu_fw_payload[%d] = {" % total)
    for i, (base, size, map_flags, payload) in enumerate(regions):
        out.append("\t/* region %d: base 0x%016x, %d bytes */" % (i, base, len(payload)))
        for at in range(0, len(payload), 12):
            out.append("\t" + " ".join("0x%02x," % b for b in payload[at:at + 12]))
    out.append("};")
    out.append("")
    out.append("#endif /* GPUFW_H */")

    with open(sys.argv[2], "w") as f:
        f.write("\n".join(out) + "\n")
    print("mkgpufw.py: the job chain at 0x%016x, slot %d, %d bytes of payload: %s" %
          (chain, slot, total, sys.argv[2]))


if __name__ == "__main__":
    main()
