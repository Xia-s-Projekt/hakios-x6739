#!/bin/bash
# Build the loader for the X6739 (MT6893).
#
# MMU off means device memory: no SIMD, strict alignment, no builtins.
# Extra arguments go to the compiler (e.g. -DXNU_WDT_SECONDS=0).
#
# The common tree (hakios-xnu-kernel) holds the loader's identity header and the linker; the
# scripts still expect the layout they were written in -- the device's mtkloader/ and tools/ at
# the top of the common tree, beside xnuloader/ -- so the paths to it are set here.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
COMMON="${HAKIOS_COMMON:-$ROOT/../refs/hakios-xnu-kernel}"

[ -f "$COMMON/xnuloader/identity.h" ] ||
	{ echo "mtkloader: no $COMMON/xnuloader/identity.h -- run tools/fetch-ios.sh identity" >&2; exit 1; }

# the linker: zig's ld.lld, as the common tree's own build uses
LLD="$COMMON/xnu-deps/host/zig/zig ld.lld"
[ -x "$COMMON/xnu-deps/host/zig/zig" ] || LLD="ld.lld"

CFLAGS="--target=aarch64-linux-gnu -ffreestanding -nostdlib -fno-builtin -fno-stack-protector -mgeneral-regs-only -mstrict-align -Os -Wall -Wextra"
# the identity header, from the common tree
CFLAGS="$CFLAGS -I$COMMON/xnuloader"

# Two headers are made here and never kept in git (.gitignore):
#  touchfw.h   the touch controller's firmware, out of YOUR phone (pull-firmware.sh puts it in
#              fw-touch/): it is the vendor's, and the controller loses it at every reset, so the
#              loader carries it (tcm.h)
#  font8x16.h  the loader's 8x16 text font, rasterized by tools/mkfont8x16.c (from a monospaced
#              bold font, which is why the bitmap is not in the repository either)
TOUCH_IMG="${TOUCH_IMG:-$ROOT/fw-touch/hdl_firmware.img}"
if [ ! -f "$HERE/touchfw.h" ]; then
	if [ -f "$TOUCH_IMG" ]; then
		python3 "$HERE/../tools/mktouchfw.py" "$TOUCH_IMG" ROMBOOT_APP_CODE "$HERE/touchfw.h"
	else
		# This board's touch is a FocalTech FT3681 on I2C0, not the reference board's TCM
		# controller, so the loader never sends it an image. The header is still needed,
		# because tcm.h includes it; an empty image is enough to compile.
		echo "mtkloader: no $TOUCH_IMG -- the touch path is off on this board, using an empty image"
		cat > "$HERE/touchfw.h" <<-'EOF'
		/* Generated by mtkloader/build.sh: this board's touch is a FocalTech FT3681 on I2C0, not
		 * the reference board's TCM controller, so the loader never sends it an image. An empty
		 * image, to compile. */
		#ifndef TOUCHFW_H
		#define TOUCHFW_H

		#include <stdint.h>

		#define TOUCH_FW_SIZE 0u
		#define TOUCH_FW_FLAG 0x0000u

		static const uint8_t touch_fw[1] = { 0 };

		#endif /* TOUCHFW_H */
		EOF
	fi
fi
#  gpufw.h   the GPU's TTRX_3485 workaround blob, out of YOUR phone (pull-firmware.sh puts it
#            in fw-gpu/): it is the vendor's, and the loader needs it to run the GPU's first job
GPU_FW_BLOB="${GPU_FW_BLOB:-$ROOT/fw-gpu/valhall-1691526.wa}"
if [ ! -f "$HERE/gpufw.h" ]; then
	if [ -f "$GPU_FW_BLOB" ]; then
		python3 "$HERE/../tools/mkgpufw.py" "$GPU_FW_BLOB" "$HERE/gpufw.h"
	else
		echo "mtkloader: no $GPU_FW_BLOB -- the GPU's first job has nothing to run"
		cat > "$HERE/gpufw.h" <<-'EOF'
		/* Generated by mtkloader/build.sh: this board's GPU blob (fw-gpu/) is not here, so the
		 * loader's GPU job probe has nothing to run. */
		#ifndef GPUFW_H
		#define GPUFW_H

		#include <stdint.h>

		#define GPU_JOB_CHAIN      0ull
		#define GPU_JOB_SLOT       0u
		#define GPU_JOB_FLAGS      0ull

		static const uint8_t gpu_fw_payload[1] = { 0 };

		#endif /* GPUFW_H */
		EOF
	fi
fi
if [ ! -f "$HERE/font8x16.h" ]; then
	# the scratch directory: never /tmp, which is a RAM-backed tmpfs on this host
	TMP=$(cd "$ROOT/.." && pwd)/refs/.tmp
	mkdir -p "$TMP"
	cc -O2 -o "$TMP/mkfont8x16" "$HERE/../tools/mkfont8x16.c" \
		$(pkg-config --cflags --libs freetype2) || \
		{ echo "mtkloader: no FreeType (pkg-config freetype2) -- cannot make the font" >&2; exit 1; }
	"$TMP/mkfont8x16" > "$HERE/font8x16.h"
fi

clang $CFLAGS "$@" -c "$HERE/start.S" -o "$HERE/start.o"
clang $CFLAGS "$@" -c "$HERE/mtkloader.c" -o "$HERE/mtkloader.o"
$LLD -T "$HERE/link.ld" --oformat binary "$HERE/start.o" "$HERE/mtkloader.o" -o "$HERE/mtkloader.bin"
ls -la "$HERE/mtkloader.bin"
